"use client";

import React, { useState } from "react";
import { Download, RefreshCw, CheckSquare, ShieldCheck, AlertTriangle } from "lucide-react";
import { Card, CardHeader, CardTitle, CardDescription, CardContent } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { evaluationService } from "@/lib/api/evaluations";

interface DecisionPackTabProps {
  evaluationId: string;
}

export function DecisionPackTab({ evaluationId }: DecisionPackTabProps) {
  const [pack, setPack] = useState<Record<string, unknown> | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const [checklist, setChecklist] = useState({
    completeness: true,
    financial: true,
    historical: true,
    rubricScored: true,
    justifications: true,
    summaryReviewed: true,
    recommendationSelected: true,
  });

  const fetchOrCreatePack = async () => {
    setLoading(true);
    setError(null);
    try {
      const data = await evaluationService.createDecisionPack(evaluationId);
      setPack(data);
    } catch (err: unknown) {
      setError(err instanceof Error ? err.message : "Failed to load evaluation decision pack.");
    } finally {
      setLoading(false);
    }
  };

  React.useEffect(() => {
    let isMounted = true;
    evaluationService
      .createDecisionPack(evaluationId)
      .then((data) => {
        if (isMounted) {
          setPack(data);
        }
      })
      .catch((err: unknown) => {
        if (isMounted) {
          setError(err instanceof Error ? err.message : "Failed to load evaluation decision pack.");
        }
      });

    return () => {
      isMounted = false;
    };
  }, [evaluationId]);

  if (loading) {
    return (
      <Card>
        <CardContent className="p-8 flex flex-col items-center justify-center space-y-3 text-xs text-slate-500">
          <RefreshCw className="h-6 w-6 animate-spin text-blue-600" />
          <span>Generating technical evaluation decision pack snapshot...</span>
        </CardContent>
      </Card>
    );
  }

  if (error) {
    return (
      <Card className="border-red-200 bg-red-50/20">
        <CardContent className="p-6 space-y-3 text-xs">
          <div className="flex items-center space-x-2 text-red-700 font-bold">
            <AlertTriangle className="h-5 w-5" />
            <span>Decision Pack Generation Failed</span>
          </div>
          <p className="text-slate-600">{error}</p>
          <Button size="sm" variant="outline" onClick={fetchOrCreatePack}>
            Retry Generation
          </Button>
        </CardContent>
      </Card>
    );
  }

  if (!pack) return null;

  const content = (pack.content as Record<string, unknown>) || {};
  const pdfUrl = evaluationService.getDecisionPackPdfUrl(evaluationId);

  return (
    <div className="space-y-6">
      {/* Pack Header */}
      <Card>
        <CardHeader className="pb-3 border-b border-slate-200">
          <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-3">
            <div>
              <div className="flex items-center space-x-2">
                <Badge variant="outline" className="font-mono text-[10px] bg-blue-50 text-blue-700">
                  Version: v{pack.version as number}
                </Badge>
                <Badge variant="outline" className="font-mono text-[10px]">
                  Hash: {(pack.input_hash as string)?.slice(0, 10)}...
                </Badge>
                <Badge variant="secondary" className="text-[10px]">
                  Status: {pack.status as string}
                </Badge>
              </div>
              <CardTitle className="text-base font-bold text-slate-900 mt-2">
                Technical Evaluation Decision Dossier
              </CardTitle>
              <CardDescription className="text-xs text-slate-500">
                Generated by: <span className="font-semibold">{pack.generated_by as string}</span> • Date: {pack.created_at as string}
              </CardDescription>
            </div>

            <div className="flex items-center space-x-2">
              <Button size="sm" variant="outline" onClick={fetchOrCreatePack} className="h-8 text-xs">
                <RefreshCw className="h-3.5 w-3.5 mr-1.5" />
                Generate New Version
              </Button>
              <Button
                size="sm"
                className="h-8 text-xs bg-blue-600 hover:bg-blue-700 text-white"
                onClick={() => window.open(pdfUrl, "_blank")}
              >
                <Download className="h-3.5 w-3.5 mr-1.5" />
                Export Dossier (PDF/HTML)
              </Button>
            </div>
          </div>
        </CardHeader>
        <CardContent className="p-4 text-xs text-slate-700 leading-relaxed">
          This Decision Pack consolidates Proposal text, P0.5 Scrutiny Checklist Findings, P0.4 Historical Benchmark Similarity, P0.6 Rubric Scorecard, and P0.8 RAG AI Evidence Analysis into a single auditable dossier for NaCCER/CMPDI review committees.
        </CardContent>
      </Card>

      {/* Safety Notice */}
      <div className="p-3.5 bg-blue-50 border border-blue-200 rounded-md text-xs text-blue-900 flex items-start space-x-2.5">
        <ShieldCheck className="h-4 w-4 text-blue-600 flex-shrink-0 mt-0.5" />
        <div>
          <strong>Reviewer Safety &amp; Governance Notice:</strong> {(content.disclaimer as string) || "This document is decision-support material. Final technical, novelty, funding, approval, and rejection decisions remain with authorized human reviewers."}
        </div>
      </div>

      {/* Final Reviewer Checklist */}
      <Card>
        <CardHeader className="pb-2">
          <CardTitle className="text-sm font-bold text-slate-900 flex items-center space-x-2">
            <CheckSquare className="h-4 w-4 text-blue-600" />
            <span>Final Reviewer Governance Checklist</span>
          </CardTitle>
          <CardDescription className="text-xs">
            Verify all evaluation components prior to submitting the final technical recommendation.
          </CardDescription>
        </CardHeader>
        <CardContent className="space-y-2.5 text-xs">
          {[
            { key: "completeness", label: "Proposal completeness scrutiny verified" },
            { key: "financial", label: "Financial arithmetic compliance verified" },
            { key: "historical", label: "Historical benchmark prior art reviewed" },
            { key: "rubricScored", label: "All mandatory rubric criteria scored" },
            { key: "justifications", label: "Low/high scores justified with evidence notes" },
            { key: "summaryReviewed", label: "Reviewer executive summary finalized" },
            { key: "recommendationSelected", label: "Human reviewer final recommendation selected" },
          ].map((item) => (
            <label key={item.key} className="flex items-center space-x-2.5 p-2 bg-slate-50 border border-slate-200 rounded cursor-pointer hover:bg-slate-100/80">
              <input
                type="checkbox"
                checked={checklist[item.key as keyof typeof checklist]}
                onChange={(e) => setChecklist({ ...checklist, [item.key]: e.target.checked })}
                className="h-4 w-4 text-blue-600 rounded border-slate-300 focus:ring-blue-500"
              />
              <span className="font-medium text-slate-800">{item.label}</span>
            </label>
          ))}
        </CardContent>
      </Card>
    </div>
  );
}
